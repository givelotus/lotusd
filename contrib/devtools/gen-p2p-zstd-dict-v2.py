"""Train an immutable raw-content dictionary from captured p2p-v2 bodies.

Requires python-zstandard and libzstd (same versions for byte reproducibility).
Capture with test/functional/p2p_zstd_dictionary_capture.py. Group 3 is held out
and is never supplied to the trainer. A standard zstd trainer supplies the
content ordering; its entropy/header bytes are removed because the protocol
uses RAWCONTENT, not a formatted zstd dictionary. Do not replace V2 bytes in
an already deployed protocol; introduce another protocol/dictionary version.
"""
import argparse
import base64
import ctypes
import ctypes.util
import hashlib
import gzip
import json
from pathlib import Path
import zstandard


def corpus(path):
    data = Path(path).read_bytes()
    if str(path).endswith('.gz'):
        data = gzip.decompress(data)
    rows = [dict(row, raw=base64.b64decode(row['body'], validate=True))
            for row in map(json.loads, data.decode().splitlines())]
    for row in rows:
        if hashlib.sha256(row['raw']).hexdigest() != row['sha256']:
            raise ValueError('corpus body SHA256 mismatch')
    return rows


def train(rows, size):
    # Remove duplicate training bodies and sort by digest so callback scheduling
    # does not affect the dictionary. No held-out group enters the trainer.
    samples = sorted({r['raw'] for r in rows if r['group'] != 3}, key=lambda b: hashlib.sha256(b).digest())
    trained = zstandard.train_dictionary(size, samples, threads=0).as_bytes()
    lib = ctypes.CDLL(ctypes.util.find_library('zstd'))
    lib.ZDICT_getDictHeaderSize.argtypes = [ctypes.c_void_p, ctypes.c_size_t]
    lib.ZDICT_getDictHeaderSize.restype = ctypes.c_size_t
    lib.ZDICT_isError.argtypes = [ctypes.c_size_t]
    lib.ZDICT_isError.restype = ctypes.c_uint
    header_size = lib.ZDICT_getDictHeaderSize(trained, len(trained))
    if lib.ZDICT_isError(header_size):
        raise RuntimeError('zstd failed to identify trained dictionary header')
    return trained[header_size:]


def header(raw):
    digest = hashlib.sha256(raw).hexdigest()
    lines = ['// Generated by contrib/devtools/gen-p2p-zstd-dict-v2.py. Do not edit.',
             '// Immutable raw-content dictionary for Lotus p2p-v2.',
             '#ifndef LOTUS_NET_ZSTD_DICT_V2_DATA_H', '#define LOTUS_NET_ZSTD_DICT_V2_DATA_H',
             '#include <cstdint>',
             f'inline constexpr const char *P2P_ZSTD_DICT_V2_SHA256 = "{digest}";',
             f'inline constexpr uint8_t P2P_ZSTD_DICT_V2[{len(raw)}] = {{']
    for i in range(0, len(raw), 12):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in raw[i:i + 12]) + ',')
    return '\n'.join(lines + ['};', '#endif // LOTUS_NET_ZSTD_DICT_V2_DATA_H', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('corpus')
    parser.add_argument('--size', type=int, default=8192)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    Path(args.output).write_text(header(train(corpus(args.corpus), args.size)))


if __name__ == '__main__':
    main()
