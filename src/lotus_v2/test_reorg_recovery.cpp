Outpoint Key(const std::vector<uint8_t> &raw) {
    Check(raw.size() >= 36, "coin entry length");
    Outpoint out;
    std::copy_n(raw.begin(), 32, out.tx_id.begin());
    for (unsigned i = 0; i < 4; ++i)
        out.index |= uint32_t(raw[32 + i]) << (8 * i);
    return out;
}
