#ifndef BITCOIN_WALLETPWA_ASSETS_H
#define BITCOIN_WALLETPWA_ASSETS_H

#include <span>
#include <string_view>

namespace walletpwa {

/** One file of the embedded wallet PWA bundle */
struct EmbeddedAsset {
    //! Path relative to /wallet/, e.g. "index.html"
    std::string_view path;
    std::string_view content_type;
    //! Strong ETag, quotes included
    std::string_view etag;
    std::string_view body;
    //! Pre-compressed gzip variant, empty if the bundle has none
    std::string_view body_gzip;
};

/**
 * The embedded bundle (generated by contrib/devtools/embed_wallet_pwa.py from
 * -DWALLET_PWA_BUNDLE), sorted by path. Empty when the build embeds none.
 */
std::span<const EmbeddedAsset> EmbeddedBundle();

/** The embedded bundle's version, or "" when the build embeds none */
std::string_view EmbeddedBundleVersion();

} // namespace walletpwa

#endif // BITCOIN_WALLETPWA_ASSETS_H
